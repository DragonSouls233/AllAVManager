def clean_chinese_filename(filename: str) -> str:
    """清洗国产文件名的广告/垃圾信息。

    Examples:
        "【麻豆传媒】王茜-高清-无水印" → "王茜"
        "精东影业_赵佳美_4K_完整版" → "赵佳美"
        "SWAG_雪碧_在线观看" → "雪碧"
    """
    stem = filename.rsplit(".", 1)[0] if "." in filename else filename
    result = stem.strip()

    # 去掉广告前缀
    for pattern in _AD_PREFIXES:
        result = re.sub(fr"^{pattern}\s*", "", result)

    # 去掉番号前缀（国产识别码）
    result = re.sub(r'^[A-Z]+-?\d+[._\s-]', '', result)

    # 去掉广告后缀
    ad_tail = [
        r'[._\s-].*?高清.*', r'[._\s-].*?无水印.*',
        r'[._\s-].*?完整.*', r'[._\s-].*?4K.*',
        r'[._\s-].*?HD.*', r'[._\s-].*?免费.*',
        r'[._\s-].*?在线.*', r'[._\s-].*?破解.*',
    ]
    for pattern in ad_tail:
        result = re.sub(pattern, '', result, flags=re.I)

    result = result.strip(' ._-')
    return result if result else stem


def extract_chinese_actors(text: str) -> list[str]:
    """从文本中提取所有已知的国产演员名。

    用于文件名、文件夹名、NFO 内容中的演员识别。
    """
    found: list[str] = []
    for actor in KNOWN_CHINESE_ACTORS:
        if actor in text:
            found.append(actor)
    return found


def normalize_chinese_code(code: str) -> str:
    """规范化国产番号。

    Examples:
        "md0263" → "MD-0263"
        "MD 263" → "MD-0263"
        "swag123" → "SWAG-123"
        "精东0123" → "JD-0123"
    """
    code = code.strip().upper()

    # 麻豆: MD-0263
    m = re.match(r"MD[-_\s]?0*(\d+)", code)
    if m:
        return f"MD-{int(m.group(1)):04d}"

    # SWAG: SWAG-123
    m = re.match(r"SWAG[-_\s]?0*(\d+)", code)
    if m:
        return f"SWAG-{int(m.group(1)):04d}"

    # 精东: JD-0123
    studio_map = {
        "精东": "JD", "天美": "TM", "果冻": "GD",
        "糖心": "TX", "蜜桃": "MT", "星空": "XK",
        "大象": "DX", "爱豆": "AD", "皇家华人": "HJHR",
    }
    for studio, prefix in studio_map.items():
        if studio in code:
            nums = re.findall(r"\d+", code)
            if nums:
                return f"{prefix}-{int(nums[-1]):04d}"

    # 已有标准格式
    m = re.match(r"([A-Z]{2,4})-(\d{3,5})", code)
    if m:
        prefix = m.group(1)
        num = int(m.group(2))
        if prefix in ("MD", "SWAG", "JD", "TM", "GD", "TX", "MT", "XK", "DX", "AD"):
            return f"{prefix}-{num:04d}"
        return f"{prefix}-{num}"

    return code
